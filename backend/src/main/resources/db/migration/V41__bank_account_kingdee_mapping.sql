-- V41: 银行账户 → 金蝶银行账号档案映射（2026-09-21，总账凭证落点方案 B 配套）。
--
-- 背景：总账凭证里挂「银行账号」必录核算维度的科目（账套维度类型 ZDY0001，维度类型=基础资料，
-- 实测 1002 银行存款挂该维度），报文必须带 CN_BANKACNT 档案编码。一家公司有多个银行账户，
-- 因此映射粒度必须到「账户级」——此前用全局默认账户 KINGDEE_DEFAULT_BANK_ACCOUNT_NUMBER
-- 属联调期占位做法（2026-09-21 用户拍板改为账户级联动）。
--
-- 值来源：① 自动匹配（按 bank_account.account_number 命中 CN_BANKACNT.FNumber，
-- 用「公司 → 金蝶组织」消歧；实测 142 个档案中 102 个编码即账号本体）；
-- ② 人工指定（虚拟账户如支付宝/微信/薪福通/分贝通无账号可匹配，须人工选一次）。
--
-- 空值语义：未映射。制证时若流水所属账户制证模式为 KINGDEE_AUTO 且本列为空 → 阻断推送并
-- 提示补映射（决策：凭证错账代价大，宁可先补）；MANUAL（纯人工制证）账户不需要本映射。
ALTER TABLE bank_account ADD COLUMN kingdee_account_number VARCHAR(128) NULL;
